import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "@/lib/env";

/**
 * File storage abstraction. Phase 1 ships the local-disk adapter (development
 * and single-server deployments). A production object-storage adapter
 * (S3-compatible) implements the same interface — see docs/ARCHITECTURE.md.
 */
export interface FileStorage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  delete(key: string): Promise<void>;
  /** URL path under which the app serves the object. */
  publicUrl(key: string): string;
}

/** Keys are generated by the server: lower-case path segments, no traversal. */
export const STORAGE_KEY_PATTERN = /^[a-z0-9]+(?:[/_.-][a-z0-9]+)*\.(webp|png|jpg|pdf)$/;

export function assertSafeKey(key: string): void {
  if (!STORAGE_KEY_PATTERN.test(key) || key.includes("..")) {
    throw new Error("Invalid storage key");
  }
}

class LocalFileStorage implements FileStorage {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    assertSafeKey(key);
    const resolved = path.resolve(this.root, key);
    if (!resolved.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Invalid storage key");
    return resolved;
  }

  async put(key: string, body: Buffer): Promise<void> {
    const target = this.resolve(key);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, body, { flag: "wx" }); // never overwrite an existing object
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await readFile(this.resolve(key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }

  publicUrl(key: string): string {
    return `/api/files/${key}`;
  }
}

let storage: FileStorage | undefined;

export function getStorage(): FileStorage {
  if (!storage) {
    const config = env();
    storage = new LocalFileStorage(path.resolve(process.cwd(), config.STORAGE_LOCAL_DIR));
  }
  return storage;
}

export { publicFileUrl } from "@/lib/files";
